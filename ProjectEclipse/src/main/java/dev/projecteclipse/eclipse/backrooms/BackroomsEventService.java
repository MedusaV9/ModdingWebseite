    /** 10 t housekeeping for the open maze: exit portal, bossbar, ambience, whispers. */
    private static void tickInside(MinecraftServer server, BackroomsState state, long remaining) {
        updateBossBar(server, state, remaining);
        ServerLevel level = server.getLevel(BackroomsDimension.BACKROOMS);
        if (level == null) {
            return;
        }

        // T-5:00: the EXIT sign hums to life (IDEAS §A5) — idempotent (pos persisted).
        if (remaining <= WARN_5M_MILLIS && state.exitPortalPos() == null) {
            spawnExitPortal(server, state, level);
        }

        BlockPos exitPos = state.exitPortalPos();
        if (exitPos != null) {
            BackroomsPortal.ambientTick(level, exitPos, level.getGameTime());
            BackroomsDread.tickExitBeacon(level, exitPos, level.getGameTime());
            var box = BackroomsPortal.collisionBox(exitPos);
            for (ServerPlayer player : List.copyOf(level.players())) {
                if (!player.isSpectator() && player.isAlive()
                        && box.intersects(player.getBoundingBox())) {
                    state.markExitUpgraded(player.getUUID());
                    exitToAnchor(server, state, player, ExitReason.EXIT_PORTAL);
                }
            }
        }

        BackroomsScare.tick(server, state, level);
        BackroomsDread.tick(level);
        tickAmbience(server, state, level);
    }

    /**
     * The EXIT sits on LEVEL 5 — deep in The Hollow (F-043). The Hollow is one wall-less
     * hall, so instead of a cell walk the pick is a hashed bearing/radius around the
     * origin, salted per instance ({@value #EXIT_MIN_RADIUS}–{@value #EXIT_MAX_RADIUS}
     * blocks out) and snapped clear of the pillar raster. Because that level is nearly
     * lightless, the portal gets the one thing the generator never gives it — a small
     * lantern ring — plus {@link BackroomsDread#tickExitBeacon}'s directional hum.
     */
    private static void spawnExitPortal(MinecraftServer server, BackroomsState state, ServerLevel level) {
        BlockPos best = findHollowExitSpot(state.mazeSeed());
        BackroomsPortal.place(level, best);
        lightExitPad(level, best);
        state.setExitPortalPos(best);
        // No chat (user decree) — the whisper caption overlay alone carries the EXIT cue.
        for (ServerPlayer player : insidePlayers(server)) {
            PacketDistributor.sendToPlayer(player, new S2CCaptionPayload(
                    "eclipse.backrooms.caption.exit", 80, S2CCaptionPayload.STYLE_WHISPER));
        }
    }

    /** Hashed point on The Hollow's walk plane, nudged out of the Säulenraster. */
    static BlockPos findHollowExitSpot(long pickSalt) {
        long hash = Long.rotateLeft(pickSalt ^ 0x0E217C0DEL, 17);
        double angle = Math.floorMod(hash, 3600L) / 3600.0D * Math.PI * 2.0D;
        double radius = EXIT_MIN_RADIUS
                + Math.floorMod(hash >>> 20, (long) (EXIT_MAX_RADIUS - EXIT_MIN_RADIUS) + 1L);
        int rawX = (int) Math.round(Math.cos(angle) * radius);
        int rawZ = (int) Math.round(Math.sin(angle) * radius);
        // Snap to the middle of a pillar bay — the raster occupies the first 2 of every 12.
        int spacing = BackroomsLayers.HOLLOW_PILLAR_SPACING;
        int x = Math.floorDiv(rawX, spacing) * spacing + spacing / 2;
        int z = Math.floorDiv(rawZ, spacing) * spacing + spacing / 2;
        return new BlockPos(x, BackroomsLayers.H_WALK_Y, z);
    }

    /**
     * The only guaranteed light on level 5: a four-lantern ring recessed into the floor
     * around the exit. ONE bounded write of four blocks at spawn time — never a sweep,
     * never per tick.
     */
    private static void lightExitPad(ServerLevel level, BlockPos base) {
        int floor = BackroomsLayers.H_BASE_TOP;
        int[][] offsets = {{3, 0}, {-3, 0}, {0, 3}, {0, -3}};
        for (int[] offset : offsets) {
            level.setBlock(new BlockPos(base.getX() + offset[0], floor, base.getZ() + offset[1]),
                    Blocks.SEA_LANTERN.defaultBlockState(), 3);
        }
    }

    /**
     * Layer-aware ambience — WET_ROOM / Poolrooms / Flooded Halls drips, The Hollow's
     * empty-cathedral rumble, the distant ballast clunk and the once-per-instance whisper
     * (IDEAS §A6) — plus the lazy per-instance loot fill of LOOT_ALCOVE barrels the player
     * walks near (the generator places them empty).
     */
    private static void tickAmbience(MinecraftServer server, BackroomsState state, ServerLevel level) {
        long now = System.currentTimeMillis();
        long seed = BackroomsMaze.worldSeed();
        for (ServerPlayer player : List.copyOf(level.players())) {
            BackroomsLayers.Layer layer = BackroomsLayers.layerOf(player.getBlockY());
            if (layer == BackroomsLayers.Layer.YELLOW_ROOMS) {
                int[] cell = BackroomsMaze.cellOf(player.blockPosition());
                if (BackroomsMaze.prefab(seed, cell[0], cell[1]) == BackroomsMaze.Prefab.WET_ROOM) {
                    BlockPos min = BackroomsMaze.cellMin(cell[0], cell[1]);
                    level.sendParticles(ParticleTypes.DRIPPING_WATER,
                            min.getX() + 1 + level.random.nextInt(6), BackroomsLayers.Y_CEIL - 0.2D,
                            min.getZ() + 1 + level.random.nextInt(6), 2, 0.4D, 0.0D, 0.4D, 0.0D);
                }
                fillNearbyLoot(level, state, seed, cell);
            } else if (layer == BackroomsLayers.Layer.POOLROOMS) {
                // The Poolrooms drip everywhere — the whole level is wet.
                level.sendParticles(ParticleTypes.DRIPPING_WATER,
                        player.getX() + level.random.nextInt(9) - 4, BackroomsLayers.P_CEIL - 0.2D,
                        player.getZ() + level.random.nextInt(9) - 4, 2, 0.4D, 0.0D, 0.4D, 0.0D);
            } else if (layer == BackroomsLayers.Layer.FLOODED_HALLS) {
                // Level 4 is defined by its dripping: heavier than the pool, and audible.
                level.sendParticles(ParticleTypes.DRIPPING_WATER,
                        player.getX() + level.random.nextInt(11) - 5, BackroomsLayers.F_CEIL - 0.2D,
                        player.getZ() + level.random.nextInt(11) - 5, 4, 0.5D, 0.0D, 0.5D, 0.0D);
                if (level.random.nextInt(4) == 0) {
                    player.playNotifySound(SoundEvents.POINTED_DRIPSTONE_DRIP_WATER,
                            SoundSource.AMBIENT, 0.5F, 0.7F + level.random.nextFloat() * 0.5F);
                }
            } else if (layer == BackroomsLayers.Layer.THE_HOLLOW) {
                // Level 5: nothing but the size of the room. A rare, very low swell.
                if (level.random.nextInt(24) == 0) {
                    player.playNotifySound(EclipseSounds.EVENT_ECLIPSE_DRONE.get(),
                            SoundSource.AMBIENT, 0.35F, 0.35F);
                }
            }
            // Distant ballast clunk (§A6.3): ~every 90 s per player, 20–30 blocks away.
            if (level.random.nextInt(180) == 0) {
                double angle = level.random.nextDouble() * Math.PI * 2.0D;
                double distance = 20.0D + level.random.nextDouble() * 10.0D;
                BlockPos clunk = player.blockPosition().offset(
                        (int) (Math.cos(angle) * distance), 0, (int) (Math.sin(angle) * distance));
                level.playSound(null, clunk, EclipseSounds.EVENT_BEAM_HUM.get(),
                        SoundSource.AMBIENT, 0.25F, 0.3F);
            }
            // WHISPER caption (§A6.5): rare, once per instance per player, after 3 min.
            long enteredAt = state.enteredAtEpochMillis(player.getUUID());
            if (enteredAt > 0L && now - enteredAt >= WHISPER_MIN_INSIDE_MILLIS
                    && level.random.nextInt(WHISPER_ODDS) == 0
                    && state.markWhispered(player.getUUID())) {
                PacketDistributor.sendToPlayer(player, new S2CCaptionPayload(
                        "eclipse.backrooms.whisper", 60, S2CCaptionPayload.STYLE_WHISPER));
            }
        }
    }

    /**
     * Fills any LOOT_ALCOVE barrel in the player's 3×3 cell neighborhood — once per
     * instance per cell, rolled with the per-instance loot seed. The generator places
     * the barrels EMPTY; this is the terrain-gen replacement for the stamp-time fill.
     */
    private static void fillNearbyLoot(ServerLevel level, BackroomsState state, long seed, int[] cell) {
        for (int dz = -1; dz <= 1; dz++) {
            for (int dx = -1; dx <= 1; dx++) {
                int cx = cell[0] + dx;
                int cz = cell[1] + dz;
                if (BackroomsMaze.prefab(seed, cx, cz) != BackroomsMaze.Prefab.LOOT_ALCOVE) {
                    continue;
                }
                BlockPos barrel = BackroomsMaze.lootBarrelPos(cx, cz);
                if (!level.getBlockState(barrel).is(Blocks.BARREL)) {
                    continue;
                }
                if (state.markLootFilled(BackroomsMaze.cellKey(cx, cz))) {
                    BackroomsMaze.fillLootBarrel(level, state.mazeSeed(), barrel, cx, cz);
                }
            }
        }
    }

    // ================================================================== flicker

    /**
     * Light-block flicker (IDEAS §A2): faulty froglight panels within
     * {@value #FLICKER_PLAYER_RANGE} blocks of a player swap to yellow glass during their
     * hashed dark window and back — REAL light changes, flag 3 (client relight). The
     * grid is infinite now, so the pass enumerates the cells AROUND each player on the
     * Yellow-Rooms layer instead of a global panel list.
     */
    private static void tickFlicker(MinecraftServer server, BackroomsState state) {
        ServerLevel level = server.getLevel(BackroomsDimension.BACKROOMS);
        if (level == null || level.players().isEmpty()) {
            return;
        }
        long seed = BackroomsMaze.worldSeed();
        long gameTime = level.getGameTime();
        int cellRange = (int) Math.ceil(FLICKER_PLAYER_RANGE / BackroomsMaze.CELL);
        Set<Long> visited = new java.util.HashSet<>();
        for (ServerPlayer player : level.players()) {
            if (BackroomsLayers.layerOf(player.getBlockY()) != BackroomsLayers.Layer.YELLOW_ROOMS) {
                continue;
            }
            int[] cell = BackroomsMaze.cellOf(player.blockPosition());
            for (int cz = cell[1] - cellRange; cz <= cell[1] + cellRange; cz++) {
                for (int cx = cell[0] - cellRange; cx <= cell[0] + cellRange; cx++) {
                    if (!visited.add(BackroomsMaze.cellKey(cx, cz))) {
                        continue;
                    }
                    for (BackroomsMaze.Panel panel : BackroomsMaze.panelsForCell(seed, cx, cz)) {
                        if (!panel.faulty()) {
                            continue;
                        }
                        boolean lit = BackroomsMaze.panelLitAt(seed, panel, gameTime);
                        var want = lit ? Blocks.OCHRE_FROGLIGHT.defaultBlockState()
                                : Blocks.YELLOW_STAINED_GLASS.defaultBlockState();
                        if (!level.getBlockState(panel.a()).is(want.getBlock())) {
                            level.setBlock(panel.a(), want, 3);
                            level.setBlock(panel.b(), want, 3);
                        }
                    }
                }
            }
        }
    }

