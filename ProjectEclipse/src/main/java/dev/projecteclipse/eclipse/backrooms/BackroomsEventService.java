    /** Wanderer cap {@value #WANDERER_CAP} + 1–2 cameo Others (IDEAS §A3), every 5 s. */
    private static void tickSpawner(MinecraftServer server, BackroomsState state) {
        ServerLevel level = server.getLevel(BackroomsDimension.BACKROOMS);
        if (level == null || level.players().isEmpty() || !BackroomsEntities.GLITCHED_WANDERER.isBound()) {
            return;
        }
        long seed = BackroomsMaze.worldSeed();
        int wanderers = 0;
        int others = 0;
        for (Entity entity : level.getAllEntities()) {
            if (entity instanceof GlitchedWandererEntity) {
                wanderers++;
            } else if (entity instanceof TheOtherEntity) {
                others++;
            }
        }
        if (wanderers < WANDERER_CAP) {
            BlockPos pos = findMazeSpawn(level, seed, WANDERER_MIN_PLAYER_DISTANCE, 0.0D);
            if (pos != null && spawnMob(level, BackroomsEntities.GLITCHED_WANDERER.get(), pos)) {
                EclipseMod.LOGGER.debug("Wanderer {}/{} spawned at {}", wanderers + 1, WANDERER_CAP, pos);
            }
        }
        if (others < THE_OTHER_CAP) {
            BlockPos pos = findMazeSpawn(level, seed, WANDERER_MIN_PLAYER_DISTANCE,
                    THE_OTHER_MIN_SPAWN_DISTANCE);
            if (pos != null && spawnMob(level, EclipseEntities.THE_OTHER.get(), pos)) {
                EclipseMod.LOGGER.debug("The Other cameo spawned at {} (backrooms)", pos);
            }
        }
    }

    /**
     * Random cell center on the LAYER a random player is exploring (the grid is
     * infinite — candidates come from cells around players, always in loaded chunks):
     * ≥ {@code minPlayerDistance} from every player, ≥ {@code minSpawnDistance} from
     * the spawn cross, never ON the spawn cross and never over a drop shaft or drain.
     */
    @Nullable
    private static BlockPos findMazeSpawn(ServerLevel level, long seed,
            double minPlayerDistance, double minSpawnDistance) {
        List<ServerPlayer> players = level.players();
        if (players.isEmpty()) {
            return null;
        }
        BlockPos spawnCenter = BackroomsMaze.cellCenter(BackroomsMaze.SPAWN_CELL, BackroomsMaze.SPAWN_CELL);
        for (int attempt = 0; attempt < 16; attempt++) {
            ServerPlayer around = players.get(level.random.nextInt(players.size()));
            BackroomsLayers.Layer layer = BackroomsLayers.layerOf(around.getBlockY());
            int[] cell = BackroomsLayers.cellOf(layer, around.blockPosition());
            // ±64 blocks on every layer (the cell side differs per layer).
            int range = Math.max(2, 64 / BackroomsLayers.cellSize(layer));
            int cx = cell[0] + level.random.nextInt(range * 2 + 1) - range;
            int cz = cell[1] + level.random.nextInt(range * 2 + 1) - range;
            // Never spawn over a descent opening — the mob would just fall a level.
            // (THE_HOLLOW is one open hall: every bay center is valid.)
            if (isOverDescent(seed, layer, cx, cz)) {
                continue;
            }
            BlockPos center = BackroomsLayers.cellCenter(layer, cx, cz);
            if (minSpawnDistance > 0.0D
                    && center.distSqr(spawnCenter) < minSpawnDistance * minSpawnDistance) {
                continue;
            }
            if (level.getChunkSource().getChunkNow(center.getX() >> 4, center.getZ() >> 4) == null) {
                continue; // unloaded cell — never force a sync chunk load for a spawn
            }
            boolean tooClose = false;
            for (ServerPlayer player : players) {
                if (center.distToCenterSqr(player.getX(), player.getY(), player.getZ())
                        < minPlayerDistance * minPlayerDistance) {
                    tooClose = true;
                    break;
                }
            }
            // Level 4's walk plane IS water (knee-deep) — a water column is spawnable there.
            var standing = level.getBlockState(center);
            if (!tooClose && (standing.isAir() || (layer == BackroomsLayers.Layer.FLOODED_HALLS
                    && !standing.getFluidState().isEmpty()))) {
                return center;
            }
        }
        return null;
    }

    /** Whether the layer cell carries this level's descent opening (pit/drain/hatch/sink). */
    private static boolean isOverDescent(long seed, BackroomsLayers.Layer layer, int cx, int cz) {
        return switch (layer) {
            case YELLOW_ROOMS -> (cx == BackroomsMaze.SPAWN_CELL && cz == BackroomsMaze.SPAWN_CELL)
                    || BackroomsMaze.prefab(seed, cx, cz) == BackroomsMaze.Prefab.DROP_SHAFT;
            case POOLROOMS -> BackroomsLayers.isDrainCell(seed, cx, cz);
            case WAREHOUSE -> BackroomsLayers.isHatchCell(seed, cx, cz);
            case FLOODED_HALLS -> BackroomsLayers.isSinkCell(seed, cx, cz);
            case THE_HOLLOW -> false;
        };
    }

    private static boolean spawnMob(ServerLevel level, EntityType<? extends Mob> type, BlockPos pos) {
        Mob mob = type.create(level);
        if (mob == null) {
            return false;
        }
        mob.moveTo(pos.getX() + 0.5D, pos.getY(), pos.getZ() + 0.5D,
                level.random.nextFloat() * 360.0F, 0.0F);
        mob.setPersistenceRequired(); // event-managed lifecycle; despawned at CLOSING
        // User decree: backrooms mobs detect players within 20 blocks only. The Wanderer's
        // own attributes already carry the cap; the shared TheOtherEntity cameo (owned by
        // entity/) gets its follow range clamped per-spawn instead of a class edit.
        var followRange = mob.getAttribute(
                net.minecraft.world.entity.ai.attributes.Attributes.FOLLOW_RANGE);
        if (followRange != null
                && followRange.getBaseValue() > GlitchedWandererEntity.DETECTION_RANGE) {
            followRange.setBaseValue(GlitchedWandererEntity.DETECTION_RANGE);
        }
        return level.addFreshEntity(mob);
    }

    // ================================================================== death protection

    /**
     * Cancels player deaths inside the backrooms BEFORE the lives pipeline can run
     * (HIGHEST priority — no drops, no Eclipse life loss, no grave, no lockout; IDEAS §A5
     * "death costs nothing: you no-clipped back out").
     */
    @SubscribeEvent(priority = EventPriority.HIGHEST)
    public static void onLivingDeath(LivingDeathEvent event) {
        if (!(event.getEntity() instanceof ServerPlayer player)
                || !BackroomsDimension.isInBackrooms(player)) {
            return;
        }
        event.setCanceled(true);
        player.setHealth(1.0F);
        player.setRemainingFireTicks(0);
        player.removeAllEffects();
        player.fallDistance = 0.0F;

        MinecraftServer server = player.server;
        BackroomsState state = BackroomsState.get(server);
        exitToAnchor(server, state, player, ExitReason.DEATH);
        EclipseMod.LOGGER.info("Protected backrooms death of {} ({}), returned to anchor",
                player.getScoreboardName(), event.getSource().getMsgId());
    }

    // ================================================================== login/logout edges

    /** Logout inside → the exit sequence runs at next login when the event is over. */
    @SubscribeEvent
    public static void onPlayerLoggedIn(PlayerEvent.PlayerLoggedInEvent event) {
        if (!(event.getEntity() instanceof ServerPlayer player)) {
            return;
        }
        MinecraftServer server = player.server;
        BackroomsState state = BackroomsState.get(server);
        if (BackroomsDimension.isInBackrooms(player)) {
            if (state.phase() != BackroomsState.Phase.OPEN) {
                exitToAnchor(server, state, player, ExitReason.CLOSED);
            }
        } else if (state.returnAnchor(player.getUUID()) != null
                && state.phase() == BackroomsState.Phase.IDLE) {
            state.removeReturnAnchor(player.getUUID()); // stale leftover, already outside
        }
    }

    @SubscribeEvent
    public static void onPlayerLoggedOut(PlayerEvent.PlayerLoggedOutEvent event) {
        if (!(event.getEntity() instanceof ServerPlayer player)) {
            return;
        }
        PENDING_LEAVE_CONFIRMS.remove(player.getUUID());
        LAST_BOUNCE_MESSAGE.remove(player.getUUID());
        BackroomsDread.forget(player.getUUID());
        removeFromBossBar(player);
    }

