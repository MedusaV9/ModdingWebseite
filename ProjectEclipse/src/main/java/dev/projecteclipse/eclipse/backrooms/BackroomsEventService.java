    /**
     * {@code /dev backrooms tp <layer>} backing (F-043 verification): drops the operator
     * on the walk plane of one of the five levels, keeping their X/Z when they are already
     * inside and searching outward for a cell whose walk block is actually standable.
     * Purely a teleport — no participation, no anchor, no lockout bookkeeping.
     */
    @Nullable
    public static Component devTeleport(MinecraftServer server, ServerPlayer player,
            BackroomsLayers.Layer layer) {
        ServerLevel level = server.getLevel(BackroomsDimension.BACKROOMS);
        if (level == null) {
            return Component.translatable("dev.eclipse.backrooms.start.no_level",
                    BackroomsDimension.BACKROOMS.location().toString());
        }
        BlockPos anchor = BackroomsDimension.isInBackrooms(player) ? player.blockPosition()
                : BackroomsMaze.cellCenter(BackroomsMaze.SPAWN_CELL, BackroomsMaze.SPAWN_CELL);
        int[] cell = BackroomsLayers.cellOf(layer, anchor);
        long seed = BackroomsMaze.worldSeed();
        BlockPos best = BackroomsLayers.cellCenter(layer, cell[0], cell[1]);
        search:
        for (int ring = 0; ring <= DEV_TP_SEARCH_RINGS; ring++) {
            for (int dz = -ring; dz <= ring; dz++) {
                for (int dx = -ring; dx <= ring; dx++) {
                    if (Math.max(Math.abs(dx), Math.abs(dz)) != ring) {
                        continue; // walk the ring, not the filled square
                    }
                    int cx = cell[0] + dx;
                    int cz = cell[1] + dz;
                    if (isOverDescent(seed, layer, cx, cz)) {
                        continue;
                    }
                    BlockPos candidate = BackroomsLayers.cellCenter(layer, cx, cz);
                    var standing = level.getBlockState(candidate);
                    if (standing.isAir() || !standing.getFluidState().isEmpty()) {
                        best = candidate;
                        break search;
                    }
                }
            }
        }
        player.teleportTo(level, best.getX() + 0.5D, best.getY(), best.getZ() + 0.5D,
                player.getYRot(), player.getXRot());
        player.fallDistance = 0.0F;
        return null;
    }

    /** {@code /dev backrooms flicker} backing — fires one blackout pulse on the caller. */
    public static void devFlicker(ServerPlayer player) {
        BackroomsDread.debugFlicker((ServerLevel) player.level(), player);
    }

    public static boolean isLockedOutNow(MinecraftServer server, Player player) {
        return BackroomsState.get(server).isLockedOut(player.getUUID());
    }
