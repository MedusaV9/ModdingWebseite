    /// order, so shadowing stays identical. The archive's fold index
    /// carries DE and EN of every Fach/Bereich title —
    /// „tresor"/„listen"/„alben" hit in the EN UI exactly like in the
    /// DE UI, and vice versa. Unknown keys fall back to the key itself,
    /// mirroring `L10n.t`.
    static func searchTitleVariants(_ key: String) -> [String] {
        for candidate in L10n.tables {
            if let text = candidate[key] {
                return text.de == text.en ? [text.de] : [text.de, text.en]
            }
        }
        return [key]
    }

